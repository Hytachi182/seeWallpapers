"""Derive compact cloth alpha runs from the painting (requires ffmpeg).

Bundling numeric masks lets the file:// renderer isolate fabric without reading
pixels from a tainted browser Canvas. Regenerate when the artwork changes.
"""
import json
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parent.parent
folder = root / 'templates' / 'pirate-cove'
width, height = 1672, 941
rgb = subprocess.run([
    'ffmpeg', '-v', 'error', '-i', str(folder / 'artwork.jpg'),
    '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-'
], check=True, capture_output=True).stdout
assert len(rgb) == width * height * 3, 'Artwork dimensions changed'
regions = [
    (0.815, 0.95, 0, 0.30, 'top', 1.8),
    (0.857, 0.926, 0.288, 0.354, 'left', 1.1),
    (0.854, 1, 0.442, 0.678, 'left', 2.1),
]
result = []
for x0, x1, y0, y1, anchor, amplitude in regions:
    sx, sy = int(x0 * width), int(y0 * height)
    sw, sh = int(x1 * width + 0.999) - sx, int(y1 * height + 0.999) - sy
    mask = bytearray(sw * sh)
    for y in range(sh):
        for x in range(sw):
            nx, ny = (sx + x) / width, (sy + y) / height
            head = 0.798 <= nx <= 0.869 and 0.255 <= ny <= 0.354
            k = ((sy + y) * width + sx + x) * 3
            r, g, b = rgb[k:k + 3]
            if not head and r > 45 and r > g * 1.45 and r > b * 1.18:
                mask[y * sw + x] = 1
    runs = []
    for y in range(4, sh - 4):
        alphas = [0] * sw
        for x in range(4, sw - 4):
            i = y * sw + x
            if not mask[i]:
                continue
            edge = 0
            for d in range(1, 5):
                if not all(mask[j] for j in (i-d, i+d, i-d*sw, i+d*sw)):
                    break
                edge = d / 4
            pinned = y / sh if anchor == 'top' else x / sw
            alphas[x] = round(edge * pinned * pinned * 15) * 17
        x = 0
        while x < sw:
            alpha, start = alphas[x], x
            while x < sw and alphas[x] == alpha:
                x += 1
            if alpha:
                runs.extend((start, y, x - start, alpha))
    result.append(dict(sx=sx, sy=sy, sw=sw, sh=sh, anchor=anchor,
                       amplitude=amplitude, runs=runs))
(folder / 'fabric-masks.js').write_text(
    '// Generated by build/generate-pirate-fabric-masks.py from artwork.jpg.\n'
    'window.pirateFabricMasks=' + json.dumps(result, separators=(',', ':')) + ';\n',
    encoding='utf-8')
print('Generated three fabric masks; head and neck excluded.')
